// The site is no longer a Flutter app. Browsers that still have the old
// Flutter service worker installed fetch this file on update: it clears the
// old caches, unregisters itself and reloads open tabs with the static site.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.map((key) => caches.delete(key)));
    await self.registration.unregister();
    const clients = await self.clients.matchAll({ type: 'window' });
    clients.forEach((client) => client.navigate(client.url));
  })());
});
